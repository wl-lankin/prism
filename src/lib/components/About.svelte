<script lang="ts" module>
  export const HOMEPAGE = 'https://wolfgang-linz.de/';
  export const REPOSITORY = 'https://github.com/wl-lankin/prism';

  export type LicenseEntry = { id?: string; name: string; version: string; license: string; repository: string; source?: string };
  type LicenseData = { rust: LicenseEntry[]; npm: LicenseEntry[]; bundled: LicenseEntry[] };
  export const GROUPS = ['bundled', 'npm', 'rust'] as const;
</script>

<script lang="ts">
  import { getVersion } from '@tauri-apps/api/app';
  import { openUrl } from '@tauri-apps/plugin-opener';
  import { onMount, tick } from 'svelte';
  import logoUrl from '../../../assets/logo.svg';
  import { t } from '../i18n';
  import Icon from './Icon.svelte';

  /** The About dialog: modal, focus stays inside, Esc or a click on the backdrop closes it
   *  and focus returns to where it was. */
  let { onclose }: { onclose: () => void } = $props();

  let dialog: HTMLDivElement | undefined = $state();
  let version = $state('');
  let view: 'about' | 'licenses' = $state('about');
  let query = $state('');
  let data: LicenseData | undefined = $state();

  // Generated by scripts/licenses.mjs; about 100 KB, so it loads only when the list opens.
  async function showLicenses() {
    view = 'licenses';
    data ??= (await import('../licenses.json')).default as LicenseData;
    await tick();
    dialog?.querySelector<HTMLElement>('.search')?.focus();
  }

  async function showAbout() {
    view = 'about';
    query = '';
    await tick();
    dialog?.querySelector<HTMLElement>('.open')?.focus();
  }

  const needle = $derived(query.trim().toLowerCase());
  const groups = $derived(
    GROUPS.map((key) => ({
      key,
      items: (data?.[key] ?? []).filter((e) => !needle || `${e.name} ${e.license}`.toLowerCase().includes(needle)),
    })).filter((g) => g.items.length > 0),
  );

  onMount(() => {
    const before = document.activeElement as HTMLElement | null;
    getVersion()
      .then((v) => (version = v))
      .catch(() => {});
    void tick().then(() => dialog?.querySelector<HTMLElement>('.close')?.focus());
    // Capture phase on the window: the dialog sees every key first, and nothing behind it
    // (Ctrl+K search, other window shortcuts) does while it is open.
    window.addEventListener('keydown', onkeydown, true);
    return () => {
      window.removeEventListener('keydown', onkeydown, true);
      before?.focus?.();
    };
  });

  function focusables(): HTMLElement[] {
    return [...(dialog?.querySelectorAll<HTMLElement>('a[href], button:not([disabled]), input, [tabindex="0"]') ?? [])];
  }

  function onkeydown(event: KeyboardEvent) {
    event.stopPropagation();
    if (event.key === 'Escape') {
      event.preventDefault();
      onclose();
      return;
    }
    if (event.key !== 'Tab') return;
    const items = focusables();
    if (items.length === 0) return;
    const first = items[0];
    const last = items[items.length - 1];
    const inside = dialog?.contains(document.activeElement);
    if (event.shiftKey && (document.activeElement === first || !inside)) {
      event.preventDefault();
      last.focus();
    } else if (!event.shiftKey && (document.activeElement === last || !inside)) {
      event.preventDefault();
      first.focus();
    }
  }

  function link(event: MouseEvent) {
    event.preventDefault();
    const href = (event.currentTarget as HTMLAnchorElement).href;
    openUrl(href).catch((err) => console.error('opening the link failed', err));
  }

  // A press that starts on the backdrop closes; one that started inside (a text selection
  // dragged out) does not.
  let pressedBackdrop = false;
</script>

<div
  class="backdrop"
  role="presentation"
  onpointerdown={(event) => (pressedBackdrop = event.target === event.currentTarget)}
  onclick={(event) => {
    if (pressedBackdrop && event.target === event.currentTarget) onclose();
    pressedBackdrop = false;
  }}
>
  <div bind:this={dialog} class="dialog" role="dialog" aria-modal="true" aria-labelledby="about-title">
    <button type="button" class="close" aria-label={t('about.close')} onclick={onclose}>
      <Icon name="close" size={18} />
    </button>

    {#if view === 'about'}
    <div class="mark" aria-hidden="true">
      <img src={logoUrl} alt="" width="76" height="76" draggable="false" />
    </div>
    <h2 id="about-title">Prism</h2>
    <p class="version">{version ? t('about.version', { version }) : ''}</p>
    <p class="tagline">{t('about.tagline')}</p>

    <p class="credit">
      {t('about.madeBy')}
      <a href={HOMEPAGE} onclick={link}>Wolfgang Linz</a>
    </p>
    <a class="github" href={REPOSITORY} onclick={link}>
      {t('about.github')}
      <Icon name="external" size={14} />
    </a>

    <button type="button" class="open" onclick={showLicenses}>{t('about.open')}</button>
    {:else}
    <section class="licenses" aria-labelledby="about-licenses">
      <button type="button" class="back" onclick={showAbout}>
        <Icon name="back" size={14} />
        {t('about.back')}
      </button>
      <h3 id="about-licenses">{t('about.open')}</h3>
      <p>{t('about.licensesLead')}</p>
      <input
        type="search"
        class="search"
        placeholder={t('about.search')}
        aria-label={t('about.search')}
        autocomplete="off"
        spellcheck="false"
        bind:value={query}
      />
      {#each groups as group (group.key)}
        <h4 data-group={group.key}>{t(`about.group.${group.key}`)} <span class="count">{group.items.length}</span></h4>
        <dl>
          {#each group.items as item (`${item.name}@${item.version}`)}
            <div>
              <dt>
                {#if item.repository}<a href={item.repository} onclick={link}>{item.name}</a>{:else}{item.name}{/if}
                {#if item.version}<span class="ver">{item.version}</span>{/if}
                {#if item.id}
                  <span class="note">{t(`about.note.${item.id}`)}</span>
                  {#if item.source}<a class="note" href={item.source} onclick={link}>{t('about.source')}</a>{/if}
                {/if}
              </dt>
              <dd>{item.license}</dd>
            </div>
          {/each}
        </dl>
      {:else}
        {#if data}<p class="none">{t('about.noMatch')}</p>{/if}
      {/each}
    </section>
    {/if}
  </div>
</div>

